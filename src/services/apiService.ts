import { StructuredRecord } from '../types';

export interface ExtractionResponse {
  success: boolean;
  data: Omit<StructuredRecord, 'id' | 'timestamp' | 'originalTranscript' | 'confirmed'> & {
    autoGeneratedTasks?: any[];
  };
  originalTranscript: string;
}

export interface CorrectionResponse {
  success: boolean;
  data: {
    updatedRecord: any;
    fieldChanged: string;
    oldValue: string;
    newValue: string;
    explanation: string;
    spokenSummary: string;
  };
}

export interface VoiceCommandResponse {
  success: boolean;
  action: string;
  target?: string;
  spokenResponse: string;
  command: string;
}

export async function extractVisitNotes(
  transcript: string,
  language: string,
  beneficiaryHint?: any
): Promise<ExtractionResponse> {
  const res = await fetch('/api/extract', {
    method: 'POST',
    headers: { 'Content-Type': 'application/json' },
    body: JSON.stringify({ transcript, language, beneficiaryHint }),
  });

  if (!res.ok) {
    const errData = await res.json().catch(() => ({}));
    throw new Error(errData.error || `Extraction failed with status ${res.status}`);
  }

  return res.json();
}

